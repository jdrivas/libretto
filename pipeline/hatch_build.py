"""Build hook: capture build metadata into src/libretto_pipeline/_version.py.

The Python counterpart of a Rust build.rs: the git short hash, whether the working tree
had uncommitted changes, and the local build time are fixed when the package is built or
installed. Refresh them with `uv sync --reinstall-package libretto-pipeline`.
"""
import subprocess
from datetime import datetime
from pathlib import Path

from hatchling.builders.hooks.plugin.interface import BuildHookInterface


def _git(root, *args):
    try:
        out = subprocess.run(["git", *args], cwd=root, capture_output=True, text=True, check=True)
    except (OSError, subprocess.CalledProcessError):
        return None
    return out.stdout.strip()


class VersionHook(BuildHookInterface):
    PLUGIN_NAME = "custom"

    def initialize(self, version, build_data):
        root = Path(self.root)
        git_hash = _git(root, "rev-parse", "--short", "HEAD") or "unknown"
        dirty = bool(_git(root, "status", "--porcelain"))
        built = datetime.now().strftime("%Y-%m-%d %H:%M:%S.%f")[:-3]
        target = root / "src" / "libretto_pipeline" / "_version.py"
        target.write_text(
            "# Generated by hatch_build.py at build time. Do not edit or commit.\n"
            f'VERSION = "{self.metadata.version}"\n'
            f'BUILD_TIME = "{built}"\n'
            f'GIT_HASH = "{git_hash}"\n'
            f"GIT_DIRTY = {dirty}\n"
        )
